export function cloneProfileAsCustom(source: ValidationProfile, customName: string): ValidationProfile {
  return {
    ...source,
    id: `custom-${Date.now().toString(36)}`,
    name: customName.trim() || `${source.name} (Copie)`,
    isBuiltIn: false,
    isVerifiedOnSample: false,
    columnMap: { ...source.columnMap },
    rules: source.rules.map((r) => ({ ...r })),
  };
}
